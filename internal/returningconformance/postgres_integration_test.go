package returningconformance

import (
	"context"
	"database/sql"
	"errors"
	"os"
	"testing"

	yourbatis "github.com/superduck-ai/yourbatis"

	_ "github.com/jackc/pgx/v5/stdlib"
)

func TestPostgresDMLReturning(t *testing.T) {
	dsn := os.Getenv("YOURBATIS_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set YOURBATIS_POSTGRES_DSN to run the PostgreSQL integration test")
	}

	ctx := context.Background()
	raw, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatalf("open PostgreSQL: %v", err)
	}
	t.Cleanup(func() {
		if err := raw.Close(); err != nil {
			t.Errorf("close PostgreSQL: %v", err)
		}
	})

	// The fixture uses a temporary table and one pooled connection so it does
	// not modify or depend on an application's persistent users table.
	raw.SetMaxOpenConns(1)
	if err := raw.PingContext(ctx); err != nil {
		t.Fatalf("ping PostgreSQL: %v", err)
	}
	if _, err := raw.ExecContext(ctx, `
		CREATE TEMPORARY TABLE users (
			id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name       TEXT NOT NULL,
			status     TEXT NOT NULL DEFAULT 'active',
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		)
	`); err != nil {
		t.Fatalf("create PostgreSQL fixture table: %v", err)
	}

	db := yourbatis.NewDB(
		raw,
		yourbatis.DialectPostgres,
		yourbatis.WithDatabaseID("postgres"),
	)
	mapper := NewReturningMapper(db)

	id, err := mapper.CreateID(ctx, "Postgres Scalar")
	if err != nil {
		t.Fatalf("create scalar ID: %v", err)
	}
	if id == 0 {
		t.Fatal("created scalar ID = 0")
	}

	created, err := mapper.Create(ctx, "Postgres Row", "pending")
	if err != nil {
		t.Fatalf("create returned row: %v", err)
	}
	if created.ID == 0 ||
		created.Name != "Postgres Row" ||
		created.Status != "pending" ||
		created.CreatedAt.IsZero() {
		t.Fatalf("created row = %#v", created)
	}

	many, err := mapper.CreateMany(ctx, []string{"Postgres One", "Postgres Two"})
	if err != nil {
		t.Fatalf("create many: %v", err)
	}
	if len(many) != 2 {
		t.Fatalf("created many = %#v", many)
	}

	pending, found, err := mapper.FindByStatus(ctx, "pending")
	if err != nil {
		t.Fatalf("find pending user: %v", err)
	}
	if !found || pending.ID != created.ID {
		t.Fatalf("find pending user = (%#v, %t), want created row", pending, found)
	}

	missing, found, err := mapper.FindByStatus(ctx, "missing")
	if err != nil {
		t.Fatalf("find missing status: %v", err)
	}
	if found || missing != (CreatedUser{}) {
		t.Fatalf("find missing status = (%#v, %t), want zero user and false", missing, found)
	}

	if _, found, err := mapper.FindByStatus(ctx, "active"); !errors.Is(err, yourbatis.ErrTooManyRows) ||
		found {
		t.Fatalf("find active users = (found %t, error %v), want false and ErrTooManyRows", found, err)
	}

	renamed, err := mapper.Rename(ctx, created.ID, "Postgres Renamed")
	if err != nil {
		t.Fatalf("rename: %v", err)
	}
	if renamed.Name != "Postgres Renamed" {
		t.Fatalf("renamed row = %#v", renamed)
	}

	deleted, err := mapper.Delete(ctx, created.ID)
	if err != nil {
		t.Fatalf("delete returning: %v", err)
	}
	if deleted.ID != created.ID {
		t.Fatalf("deleted row = %#v", deleted)
	}

	forcedRollback := errors.New("force PostgreSQL rollback")
	var rolledBackID int64
	err = db.Transaction(ctx, func(tx yourbatis.Executor) error {
		row, err := NewReturningMapper(tx).Create(ctx, "Postgres Rollback", "pending")
		if err != nil {
			return err
		}
		rolledBackID = row.ID
		return forcedRollback
	})
	if !errors.Is(err, forcedRollback) {
		t.Fatalf("transaction error = %v, want forced rollback", err)
	}
	if _, err := mapper.Get(ctx, rolledBackID); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("rolled-back row lookup error = %v, want sql.ErrNoRows", err)
	}
}
