package user

import (
	"context"
	"database/sql"
	"errors"
	"os"
	"strings"
	"testing"

	yourbatis "github.com/superduck-ai/yourbatis"

	_ "github.com/jackc/pgx/v5/stdlib"
)

func TestUserMapperPostgresSearchEachAndCreateMany(t *testing.T) {
	dsn := os.Getenv("YOURBATIS_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set YOURBATIS_POSTGRES_DSN to run the PostgreSQL integration test")
	}
	debugOutput := captureEnvironmentDebugOutput(t)

	ctx := context.Background()
	raw, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatalf("open PostgreSQL: %v", err)
	}
	t.Cleanup(func() {
		if err := raw.Close(); err != nil {
			t.Errorf("close PostgreSQL: %v", err)
		}
	})
	raw.SetMaxOpenConns(1)
	if err := raw.PingContext(ctx); err != nil {
		t.Fatalf("ping PostgreSQL: %v", err)
	}
	if _, err := raw.ExecContext(ctx, `
		CREATE TEMPORARY TABLE users (
			id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name       TEXT NOT NULL,
			email      TEXT NOT NULL UNIQUE,
			status     TEXT NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMPTZ
		)
	`); err != nil {
		t.Fatalf("create PostgreSQL fixture table: %v", err)
	}

	var firstID int64
	if err := raw.QueryRowContext(
		ctx,
		"INSERT INTO users (name, email, status) VALUES ($1, $2, $3) RETURNING id",
		"Postgres First",
		"postgres-first@example.com",
		UserStatusActive,
	).Scan(&firstID); err != nil {
		t.Fatalf("insert first PostgreSQL fixture: %v", err)
	}
	var secondID int64
	if err := raw.QueryRowContext(
		ctx,
		"INSERT INTO users (name, email, status) VALUES ($1, $2, $3) RETURNING id",
		"Postgres Second",
		"postgres-second@example.com",
		UserStatusActive,
	).Scan(&secondID); err != nil {
		t.Fatalf("insert second PostgreSQL fixture: %v", err)
	}

	logger := &sqlEventRecorder{}
	db := yourbatis.NewDB(
		raw,
		yourbatis.DialectPostgres,
		yourbatis.WithDatabaseID("postgres"),
		yourbatis.WithLogger(logger),
	)
	mapper := NewUserMapper(db)
	users, err := mapper.Search(ctx, SearchUserParams{
		IDs:   []int64{0, -1},
		Limit: 10,
	})
	if err != nil {
		t.Fatalf("search PostgreSQL with all IDs filtered out: %v", err)
	}
	if len(users) != 2 {
		t.Fatalf("all-filtered IDs should omit the PostgreSQL ID predicate: %#v", users)
	}

	var streamedIDs []int64
	err = mapper.SearchEach(ctx, SearchUserParams{}, func(current User) error {
		streamedIDs = append(streamedIDs, current.ID)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(streamedIDs) != 2 ||
		streamedIDs[0] != firstID ||
		streamedIDs[1] != secondID {
		t.Fatalf("streamed IDs = %v, want [%d %d]", streamedIDs, firstID, secondID)
	}

	yieldErr := errors.New("stop PostgreSQL stream")
	err = mapper.SearchEach(ctx, SearchUserParams{}, func(User) error {
		return yieldErr
	})
	if err != yieldErr {
		t.Fatalf("yield error = %#v, want original error %#v", err, yieldErr)
	}
	if event := logger.find("UserMapper.SearchEach"); event == nil ||
		event.Statement.Kind != yourbatis.StatementSelect {
		t.Fatalf("SearchEach log event = %#v", event)
	}

	batchParams := []CreateUserParams{
		{
			Name:   "Postgres Batch One",
			Email:  "postgres-batch-one@example.com",
			Status: UserStatusDisabled,
		},
		{
			Name:   "Postgres Batch Two",
			Email:  "postgres-batch-two@example.com",
			Status: UserStatusDeleted,
		},
	}
	affected, err := mapper.CreateMany(ctx, batchParams)
	if err != nil {
		t.Fatalf("create many PostgreSQL users: %v", err)
	}
	if affected != int64(len(batchParams)) {
		t.Fatalf("CreateMany affected rows = %d, want %d", affected, len(batchParams))
	}
	assertEnvironmentDebugOutput(
		t,
		debugOutput.String(),
		[]string{
			"Statement: UserMapper.CreateMany",
			"INSERT INTO users",
			"Postgres Batch One",
			"<redacted>",
		},
		[]string{"postgres-batch-one@example.com"},
	)
	for _, params := range batchParams {
		created, found, err := mapper.FindByEmail(ctx, params.Email)
		if err != nil {
			t.Fatalf("find batch-created PostgreSQL user %q: %v", params.Email, err)
		}
		if !found ||
			created.Name != params.Name ||
			created.Status != params.Status {
			t.Fatalf("batch-created PostgreSQL user = (%#v, %t), want %#v", created, found, params)
		}
	}
	names, err := mapper.ListNamesOrderedBy(ctx, yourbatis.MustIdentifier("name"))
	if err != nil {
		t.Fatalf("list PostgreSQL names by dynamic identifier: %v", err)
	}
	if got := strings.Join(names, ","); got != "Postgres Batch One,Postgres Batch Two,Postgres First,Postgres Second" {
		t.Fatalf("names ordered by dynamic identifier = %q", got)
	}
	event := logger.find("UserMapper.CreateMany")
	if event == nil || len(event.Args) != 6 ||
		!event.Args[1].Sensitive ||
		!event.Args[4].Sensitive {
		t.Fatalf("PostgreSQL CreateMany log event = %#v", event)
	}

	err = db.Transaction(ctx, func(tx yourbatis.Executor) error {
		_, err := NewUserMapper(tx).CreateMany(ctx, []CreateUserParams{
			{
				Name:   "Postgres Committed One",
				Email:  "postgres-committed-one@example.com",
				Status: UserStatusActive,
			},
			{
				Name:   "Postgres Committed Two",
				Email:  "postgres-committed-two@example.com",
				Status: UserStatusActive,
			},
		})
		return err
	})
	if err != nil {
		t.Fatalf("commit PostgreSQL CreateMany transaction: %v", err)
	}
	if _, found, err := mapper.FindByEmail(
		ctx,
		"postgres-committed-two@example.com",
	); err != nil || !found {
		t.Fatalf("find committed PostgreSQL CreateMany user = (found %t, error %v)", found, err)
	}

	batchRollback := errors.New("force PostgreSQL CreateMany rollback")
	err = db.Transaction(ctx, func(tx yourbatis.Executor) error {
		if _, err := NewUserMapper(tx).CreateMany(ctx, []CreateUserParams{
			{
				Name:   "Postgres Rolled Back One",
				Email:  "postgres-rolled-back-one@example.com",
				Status: UserStatusActive,
			},
			{
				Name:   "Postgres Rolled Back Two",
				Email:  "postgres-rolled-back-two@example.com",
				Status: UserStatusActive,
			},
		}); err != nil {
			return err
		}
		return batchRollback
	})
	if !errors.Is(err, batchRollback) {
		t.Fatalf("PostgreSQL CreateMany rollback error = %v, want %v", err, batchRollback)
	}
	if _, found, err := mapper.FindByEmail(
		ctx,
		"postgres-rolled-back-one@example.com",
	); err != nil || found {
		t.Fatalf(
			"find rolled-back PostgreSQL CreateMany user = (found %t, error %v)",
			found,
			err,
		)
	}

	disabled := UserStatusDisabled
	err = db.TransactionOptions(ctx, &sql.TxOptions{}, func(tx yourbatis.Executor) error {
		txMapper := NewUserMapper(tx)
		if _, err := txMapper.UpdateStatus(ctx, firstID, disabled); err != nil {
			return err
		}
		found := false
		if err := txMapper.SearchEach(
			ctx,
			SearchUserParams{Status: &disabled},
			func(current User) error {
				found = found || current.ID == firstID
				return nil
			},
		); err != nil {
			return err
		}
		if !found {
			return errors.New("stream did not observe transaction update")
		}
		return nil
	})
	if err != nil {
		t.Fatalf("stream transaction commit: %v", err)
	}
	committed, err := mapper.GetByID(ctx, firstID)
	if err != nil {
		t.Fatal(err)
	}
	if committed.Status != disabled {
		t.Fatalf("committed status = %q, want %q", committed.Status, disabled)
	}

	active := UserStatusActive
	err = db.Transaction(ctx, func(tx yourbatis.Executor) error {
		txMapper := NewUserMapper(tx)
		if _, err := txMapper.UpdateStatus(ctx, firstID, active); err != nil {
			return err
		}
		return txMapper.SearchEach(
			ctx,
			SearchUserParams{Status: &active},
			func(User) error {
				return yieldErr
			},
		)
	})
	if err != yieldErr {
		t.Fatalf("stream transaction rollback error = %#v, want %#v", err, yieldErr)
	}
	rolledBack, err := mapper.GetByID(ctx, firstID)
	if err != nil {
		t.Fatal(err)
	}
	if rolledBack.Status != disabled {
		t.Fatalf("status after rollback = %q, want %q", rolledBack.Status, disabled)
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatalf("begin manual PostgreSQL transaction: %v", err)
	}
	txMapper := NewUserMapper(tx)
	if _, err := txMapper.UpdateStatus(ctx, firstID, active); err != nil {
		_ = tx.Rollback()
		t.Fatalf("update in manual PostgreSQL transaction: %v", err)
	}
	if _, err := tx.SQLTx().ExecContext(ctx, `
		INSERT INTO users (name, email, status)
		VALUES ($1, $2, $3)
	`, "Postgres SQLTx Commit", "postgres-sqltx-commit@example.com", active); err != nil {
		_ = tx.Rollback()
		t.Fatalf("create through SQLTx in manual PostgreSQL transaction: %v", err)
	}
	if err := tx.Commit(); err != nil {
		t.Fatalf("commit manual PostgreSQL transaction: %v", err)
	}
	manuallyCommitted, err := mapper.GetByID(ctx, firstID)
	if err != nil {
		t.Fatal(err)
	}
	if manuallyCommitted.Status != active {
		t.Fatalf("status after manual commit = %q, want %q", manuallyCommitted.Status, active)
	}
	if _, found, err := mapper.FindByEmail(ctx, "postgres-sqltx-commit@example.com"); err != nil || !found {
		t.Fatalf("find SQLTx-committed PostgreSQL user = (found %t, error %v)", found, err)
	}

	tx, err = db.BeginTx(ctx, &sql.TxOptions{})
	if err != nil {
		t.Fatalf("begin manual PostgreSQL rollback transaction: %v", err)
	}
	txMapper = NewUserMapper(tx)
	if _, err := txMapper.UpdateStatus(ctx, firstID, disabled); err != nil {
		_ = tx.Rollback()
		t.Fatalf("update before manual PostgreSQL rollback: %v", err)
	}
	if _, err := tx.SQLTx().ExecContext(ctx, `
		INSERT INTO users (name, email, status)
		VALUES ($1, $2, $3)
	`, "Postgres SQLTx Rollback", "postgres-sqltx-rollback@example.com", disabled); err != nil {
		_ = tx.Rollback()
		t.Fatalf("create through SQLTx before manual PostgreSQL rollback: %v", err)
	}
	if err := tx.Rollback(); err != nil {
		t.Fatalf("manual PostgreSQL rollback: %v", err)
	}
	manuallyRolledBack, err := mapper.GetByID(ctx, firstID)
	if err != nil {
		t.Fatal(err)
	}
	if manuallyRolledBack.Status != active {
		t.Fatalf("status after manual rollback = %q, want %q", manuallyRolledBack.Status, active)
	}
	if _, found, err := mapper.FindByEmail(ctx, "postgres-sqltx-rollback@example.com"); err != nil || found {
		t.Fatalf("find SQLTx-rolled-back PostgreSQL user = (found %t, error %v)", found, err)
	}
	if err := db.Close(); err != nil {
		t.Fatalf("close PostgreSQL runtime: %v", err)
	}
	if _, err := mapper.Search(ctx, SearchUserParams{}); err == nil {
		t.Fatal("query after closing PostgreSQL runtime succeeded")
	}
}
